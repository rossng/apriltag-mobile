apriltag_family_t *tag25h7_create(void) {
    apriltag_family_t *tf = tag25h9_create();
    free(tf->name);
    tf->name = strdup("tag25h7");
    tf->h = 7;
    tf->ncodes = 242;
    tf->codes = calloc(tf->ncodes, sizeof(uint64_t));
    for (uint32_t id = 0; id < tf->ncodes; id++) {
        for (uint32_t i = 0; i < tf->nbits; i++) {
            uint32_t old_bit = (tf->bit_y[i] - 1) * 5 + tf->bit_x[i] - 1;
            uint64_t bit = (legacy_codes[id] >> (24 - old_bit)) & 1;
            tf->codes[id] |= bit << (24 - i);
        }
    }
    return tf;
}

void tag25h7_destroy(apriltag_family_t *tf) {
    free(tf->codes);
    tag25h9_destroy(tf);
}
